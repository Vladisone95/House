"""Regenerate the style variants (ADR 0011) from the current layout.

    uv run python scripts/restyle/run.py            # every style in scripts/restyle/styles/
    uv run python scripts/restyle/run.py V7 V9      # only these

Each styles/<KEY>.py defines SPEC (format: restyle_lib docstring). The styles' own finishes are written into a
generated block at the end of data/apartment.toml; then data/variants/<KEY>.toml is rewritten from the layout
(style_of, default V1) - so after moving furniture in V1, re-run this and every style follows.
"""

import runpy
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from restyle_lib import ROOT, finishes_toml, make  # noqa: E402

BEGIN = "# >>> style-variant finishes - generated by scripts/restyle/run.py, edit the style files instead"
END = "# <<< style-variant finishes"


def _key(p: Path) -> tuple:
    return (p.stem[0], int(p.stem[1:]) if p.stem[1:].isdigit() else 0)


def load_specs() -> dict[str, dict]:
    files = sorted((HERE / "styles").glob("V*.py"), key=_key)
    return {p.stem: runpy.run_path(str(p), run_name="style")["SPEC"] for p in files}


def write_finishes(specs: dict[str, dict]) -> int:
    path = ROOT / "data" / "apartment.toml"
    text = path.read_text(encoding="utf-8")
    if BEGIN in text:
        text = text[: text.index(BEGIN)].rstrip() + "\n"
    block = "".join(f"\n# {k} - {s['name']}" + finishes_toml(s) for k, s in specs.items() if s.get("finishes"))
    path.write_text(f"{text}\n{BEGIN}\n{block}\n{END}\n", encoding="utf-8")
    return sum(len(s.get("finishes", {})) for s in specs.values())


def main(keys: list[str]) -> None:
    specs = load_specs()
    n = write_finishes(specs)  # always all styles' finishes, so a partial run never drops another style's
    print(f"{n} style finishes -> data/apartment.toml")
    for k, spec in specs.items():
        if not keys or k in keys:
            make(k, spec, source=spec.get("style_of", "V1"))


if __name__ == "__main__":
    main(sys.argv[1:])
